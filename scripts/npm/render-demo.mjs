/** Render the real UI using an isolated synthetic workspace. No model calls. */
import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../", import.meta.url));
const directory = mkdtempSync(join(tmpdir(), "relay-demo-render-"));
const output = join(root, "docs/assets/workspace");
mkdirSync(output, { recursive: true });
const cli = join(root, "dist/cli.js");
const run = (args) =>
  execFileSync(process.execPath, [cli, ...args, "--data-dir", directory], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
let browser;
try {
  const demo = JSON.parse(run(["demo"]));
  const url = run(["ui", "--no-open"]).trim();
  browser = await chromium.launch(
    process.env.RELAY_CHROME
      ? { executablePath: process.env.RELAY_CHROME }
      : {},
  );
  const page = await browser.newPage({
    viewport: { width: 1440, height: 1120 },
    deviceScaleFactor: 1,
    colorScheme: "light",
    reducedMotion: "reduce",
  });
  await page.goto(url);
  await page
    .getByRole("heading", { name: "Pick up where you left off." })
    .waitFor();
  await page.locator(`[data-session="${demo.sessionId}"]`).click();
  await page.screenshot({ path: join(output, "threads.png") });
  await page.locator('[data-evidence="user-2"]').check();
  await page.locator('[data-evidence="tool-3"]').check();
  await page.getByRole("button", { name: "Review handoff →" }).click();
  await page.locator('[data-draft="title"]').fill("Continue webhook recovery");
  await page
    .locator('[data-draft="goal"]')
    .fill(
      "Prevent duplicate webhook charges across retries and worker restarts.",
    );
  await page.getByRole("button", { name: "+ Add instruction" }).click();
  await page.locator('[data-field="key"]').fill("retention");
  await page
    .locator('[data-field="text"]')
    .fill(
      "Retain idempotency keys for 7 days. This supersedes the original 24-hour requirement.",
    );
  await page
    .locator('[data-draft="criteria"]')
    .fill(
      "One charge per provider event, including simultaneous duplicate delivery.\nReplay after a worker restart does not create a second charge.",
    );
  await page
    .locator('[data-draft="openWork"]')
    .fill(
      "Implement durable claim handling.\nRun the concurrency and crash-recovery tests.",
    );
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(output, "review.png") });
  await page.locator("#review-confirm").check();
  await page
    .getByRole("button", { name: "Save checkpoint & offer handoff" })
    .click();
  await page
    .getByRole("heading", { name: "A clean start, with the context." })
    .waitFor();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(output, "handoff.png") });
  await page.getByRole("button", { name: "Architecture", exact: true }).click();
  await page.screenshot({ path: join(output, "architecture.png") });
  await page.getByRole("button", { name: "Threads", exact: true }).click();
  await page.getByRole("button", { name: "Toggle color theme" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(output, "mobile-dark.png") });
  writeFileSync(
    join(output, "README.md"),
    "# Real workspace demo\n\nGenerated by `npm run demo:render` against an isolated synthetic SQLite workspace. The flow selects a corrected seven-day retention instruction, reviews its sources, saves a checkpoint and offers a Codex handoff. No model calls or task execution occur. The GIF uses the same screenshots with playback timing set for readability.\n\nRebuild: `npm run demo:render`, then `python3 scripts/npm/build-demo-gif.py` (Pillow required). Use `RELAY_CHROME=/path/to/chrome` for an installed Chromium browser.\n",
  );
  console.log("Rendered five real workspace views using synthetic data.");
} finally {
  await browser?.close();
  try {
    run(["stop"]);
    await new Promise((r) => setTimeout(r, 400));
  } catch {}
  rmSync(directory, { recursive: true, force: true });
}
